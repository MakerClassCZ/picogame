# Quest tutorial hero "sheet": the 6 hand-drawn frames laid out in a single row, exactly
# how frames sit side by side in a real sprite-sheet (index = position, 0..5). No labels
# -- just the strip, so the reader sees what gets animated. The masks are the same ones
# inlined in tutorials/03-quest/step4_anim.py (kept in sync by eye; this image makes any
# drift obvious). Regenerate from a tree with sim/ + lib (e.g. repos/picogame):
#   PYTHONPATH="$PWD/lib:$PWD/sim" python3 sim/run.py \
#       ../picogame-web/docs/img/gen_quest_hero.py --shot "$PWD/../picogame-web/docs/img/tut_quest_hero.png"
import picogame as pg, picogame_game, picogame_shapes as shp

HERO_COLOR = pg.rgb565(235, 90, 70)
DOWN_A = ["................", ".....####.......", "....######......", "....######......",
          "....#.##.#......", "....######......", ".....####.......", "...########.....",
          "..##########....", "..##########....", "..##########....", "...########.....",
          "....##..##......", "...###..##......", "..###...##......", "..##............"]
DOWN_B = ["................", ".....####.......", "....######......", "....######......",
          "....#.##.#......", "....######......", ".....####.......", "...########.....",
          "..##########....", "..##########....", "..##########....", "...########.....",
          "....##..##......", "....##..###.....", "....##...###....", "..........##...."]
UP_A = ["................", ".....####.......", "....######......", "....######......",
        "....######......", "....######......", ".....####.......", "...########.....",
        "..##########....", "..##########....", "..##########....", "...########.....",
        "....##..##......", "...###..##......", "..###...##......", "..##............"]
UP_B = ["................", ".....####.......", "....######......", "....######......",
        "....######......", "....######......", ".....####.......", "...########.....",
        "..##########....", "..##########....", "..##########....", "...########.....",
        "....##..##......", "....##..###.....", "....##...###....", "..........##...."]
SIDE_A = ["................", ".....####.......", "....#####.......", "....######......",
          "....#####.#.....", "....######......", ".....####.......", "....######......",
          "....######.#....", "....######.#....", "....######......", ".....####.......",
          "...##....##.....", "..##......##....", "..##......##....", "..#........#...."]
SIDE_B = ["................", ".....####.......", "....#####.......", "....######......",
          "....#####.#.....", "....######......", ".....####.......", "....######......",
          "....######......", "....######......", "....######......", ".....####.......",
          ".....####.......", ".....####.......", "....##..##......", "....#....#......"]

FRAMES = [DOWN_A, DOWN_B, UP_A, UP_B, SIDE_A, SIDE_B]   # index 0..5, left to right
SCALE = 3
GAP = 2                                                 # thin gap so the 6 frames are countable
BG = pg.rgb565(24, 26, 34)
scene, _, _ = picogame_game.setup(background=BG)
cell = 16 * SCALE
x0 = (320 - (len(FRAMES) * cell + (len(FRAMES) - 1) * GAP)) // 2   # centre the strip
y0 = (240 - cell) // 2
for i, mask in enumerate(FRAMES):
    s = pg.Sprite(shp.from_mask(mask, HERO_COLOR), x0 + i * (cell + GAP), y0)
    s.scale = SCALE
    scene.add(s)
while True:
    scene.refresh()
